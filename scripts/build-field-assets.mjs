import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = process.cwd();
const sourceDir = path.join(root, 'field-sources');
const outputDir = path.join(root, 'public', 'field');
const generatedFile = path.join(root, 'lib', 'field-assets.generated.ts');
const padding = 8;
const atlasWidth = 1024;

const objects = [
  ['bush', 'semak.png', 180, 118],
  ['tree', 'pohon.png', 150, 184],
  ['crates', 'crates.png', 124, 104],
  ['drain', 'got.png', 252, 88],
  ['lamp', 'lampu.png', 74, 152],
  ['bunting', 'lines.png', 224, 116],
  ['clothesline', 'jemuran.png', 210, 170],
  ['bucket', 'ember.png', 76, 82],
  ['trash', 'tempat sampaj.png', 74, 112],
  ['plant', 'pot bunga.png', 88, 112],
  ['fortGreen', 'benteng tim hijau.png', 194, 188],
  ['fortRed', 'benteng tim merah.png', 194, 188],
  ['guardPost', 'pos ronda.png', 222, 198],
  ['hall', 'balai.png', 238, 198],
  ['warung', 'warung.png', 238, 198],
];

const grounds = [
  ['grass', { left: 15, top: 55, width: 690, height: 460 }],
  ['dirt', { left: 742, top: 55, width: 690, height: 460 }],
  ['paving', { left: 15, top: 578, width: 690, height: 460 }],
  ['concrete', { left: 742, top: 578, width: 690, height: 460 }],
];

const nextPowerOfTwo = value => 2 ** Math.ceil(Math.log2(value));
await mkdir(outputDir, { recursive: true });

const prepared = [];
for (const [id, filename, width, height] of objects) {
  const { data, info } = await sharp(path.join(sourceDir, filename))
    .trim({ background: { r: 0, g: 0, b: 0, alpha: 0 }, threshold: 1 })
    .resize({ width, height, fit: 'inside', withoutEnlargement: true })
    .ensureAlpha()
    .png()
    .toBuffer({ resolveWithObject: true });
  prepared.push({ id, data, width: info.width, height: info.height });
}

prepared.sort((a, b) => b.height - a.height || b.width - a.width || a.id.localeCompare(b.id));
let x = padding;
let y = padding;
let shelfHeight = 0;
const atlasAssets = {};
const composites = [];
for (const asset of prepared) {
  if (x + asset.width + padding > atlasWidth) {
    x = padding;
    y += shelfHeight + padding;
    shelfHeight = 0;
  }
  atlasAssets[asset.id] = { x, y, width: asset.width, height: asset.height };
  composites.push({ input: asset.data, left: x, top: y });
  x += asset.width + padding;
  shelfHeight = Math.max(shelfHeight, asset.height);
}
const atlasHeight = nextPowerOfTwo(y + shelfHeight + padding);
await sharp({ create: { width: atlasWidth, height: atlasHeight, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(composites)
  .webp({ quality: 82, alphaQuality: 92, effort: 6, smartSubsample: true })
  .toFile(path.join(outputDir, 'objects.webp'));

const tileWidth = 384;
const tileHeight = 256;
const groundSource = sharp(path.join(sourceDir, 'tiles latar.png'));
const groundTiles = {};
const groundComposites = [];
for (let index = 0; index < grounds.length; index++) {
  const [id, crop] = grounds[index];
  const data = await groundSource.clone().extract(crop).resize(tileWidth, tileHeight, { fit: 'fill' }).png().toBuffer();
  const tileX = (index % 2) * tileWidth;
  const tileY = Math.floor(index / 2) * tileHeight;
  groundTiles[id] = { x: tileX, y: tileY, width: tileWidth, height: tileHeight };
  groundComposites.push({ input: data, left: tileX, top: tileY });
}
await sharp({ create: { width: tileWidth * 2, height: tileHeight * 2, channels: 3, background: '#737354' } })
  .composite(groundComposites)
  .webp({ quality: 74, effort: 6, smartSubsample: true })
  .toFile(path.join(outputDir, 'grounds.webp'));

const manifest = {
  version: 1,
  objects: { file: 'objects.webp', width: atlasWidth, height: atlasHeight, assets: atlasAssets },
  grounds: { file: 'grounds.webp', width: tileWidth * 2, height: tileHeight * 2, tiles: groundTiles },
};
await writeFile(path.join(outputDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

const ts = `// Generated by scripts/build-field-assets.mjs. Do not edit by hand.\n` +
  `export const FIELD_ASSET_VERSION = ${manifest.version} as const;\n` +
  `export const FIELD_OBJECT_ATLAS = ${JSON.stringify({ width: atlasWidth, height: atlasHeight, assets: atlasAssets }, null, 2)} as const;\n` +
  `export const FIELD_GROUND_ATLAS = ${JSON.stringify({ width: tileWidth * 2, height: tileHeight * 2, tiles: groundTiles }, null, 2)} as const;\n` +
  `export type FieldAssetId = keyof typeof FIELD_OBJECT_ATLAS.assets;\n` +
  `export type GroundTileId = keyof typeof FIELD_GROUND_ATLAS.tiles;\n`;
await writeFile(generatedFile, ts);

console.log(`Field runtime built: objects ${atlasWidth}x${atlasHeight}, grounds ${tileWidth * 2}x${tileHeight * 2}.`);
