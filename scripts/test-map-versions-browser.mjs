import fs from 'node:fs';
import assert from 'node:assert/strict';
import {startMapStudio} from './map-studio/server.mjs';
const {chromium}=await import(process.env.BENTENG_PLAYWRIGHT_MODULE??'playwright');
const before=fs.readFileSync('config/map-studio.json'),{server,origin}=await startMapStudio(0);
let browser;const errors=[],writes=[],out='outputs/map-versions';fs.mkdirSync(out,{recursive:true});
try{
  browser=await chromium.launch({headless:true,executablePath:process.env.BENTENG_CHROME_PATH});
  const page=await browser.newPage({viewport:{width:1600,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.method()==='POST')writes.push(r.url());});
  await page.goto(origin);await page.getByText('Map Studio siap',{exact:false}).waitFor();
  const catalog=await (await fetch(origin+'/api/templates')).json(),state=await (await fetch(origin+'/api/state')).json();
  const native=catalog.builtinTemplates.find(m=>m.replaces==='taman'),saved=state.document.maps.find(m=>m.replaces==='taman');
  assert.ok(saved&&!saved.enabled,'Taman QA expects an inactive saved draft');
  await page.locator('#maps').selectOption('builtin:taman');
  assert.match(await page.locator('#versionBadge').innerText(),/AKTIF LOKAL.*HANYA BACA/);
  assert.equal(await page.locator('#objects button').count(),native.objects.length+4);
  assert.ok(await page.locator('#save').isDisabled());assert.ok(await page.locator('#resetMap').isDisabled());
  assert.ok(await page.locator('#mapName').isDisabled());
  await page.locator('#cleanPreview').check();await page.screenshot({path:out+'/taman-active.png'});
  await page.locator('#editVersion').click();
  assert.equal(await page.locator('#maps').inputValue(),saved.id);
  assert.match(await page.locator('#versionBadge').innerText(),/DRAFT.*NONAKTIF/);
  assert.equal(await page.locator('#objects button').count(),saved.objects.length+4);
  assert.ok(await page.locator('#save').isEnabled());assert.ok(await page.locator('#mapName').isEnabled());
  await page.screenshot({path:out+'/taman-draft.png'});
  await page.locator('#mapName').fill('Unwritten QA draft');
  page.once('dialog',d=>d.dismiss());await page.locator('#maps').selectOption('builtin:taman');
  assert.equal(await page.locator('#maps').inputValue(),saved.id);assert.equal(await page.locator('#mapName').inputValue(),'Unwritten QA draft');
  page.once('dialog',d=>d.accept());await page.locator('#maps').selectOption('builtin:taman');
  assert.equal(await page.locator('#objects button').count(),native.objects.length+4);
  await page.locator('#maps').selectOption('live:studio-kampung-2420b8cf');
  assert.ok(await page.locator('#save').isDisabled());await page.locator('#editVersion').click();
  assert.equal(await page.locator('#maps').inputValue(),'studio-kampung-2420b8cf');assert.ok(await page.locator('#save').isEnabled());
  await page.locator('#showArchived').check();await page.locator('#maps').selectOption('builtin:kampung3d');
  assert.ok(await page.locator('#editVersion').isHidden());assert.ok(await page.locator('#save').isDisabled());
  await page.locator('#maps').selectOption('builtin:kanal2');assert.ok(await page.locator('#editVersion').isVisible());
  // Detached API fixture: creating a new draft must not silently activate it.
  await page.route('**/api/state',route=>route.fulfill({json:{...state,document:{...state.document,maps:state.document.maps.filter(m=>m.replaces!=='pasar')}}}));
  await page.reload();await page.getByText('Map Studio siap',{exact:false}).waitFor();
  await page.locator('#maps').selectOption('builtin:pasar');
  assert.equal(await page.locator('#editVersion').innerText(),'Buat draft dari versi ini');
  await page.locator('#editVersion').click();
  assert.equal(await page.locator('#maps').inputValue(),'studio-edit-pasar');
  assert.ok(!await page.locator('#enabled').isChecked());assert.match(await page.locator('#saveState').innerText(),/Belum disimpan/);
  assert.ok(await page.locator('#save').isEnabled());
  assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);assert.ok(before.equals(fs.readFileSync('config/map-studio.json')));
  console.log('PASS active native vs saved draft, readonly, edit handoff, cancel dirty switch, custom active map, 3D guard; no writes');
}finally{await browser?.close();await new Promise(r=>server.close(r));assert.ok(before.equals(fs.readFileSync('config/map-studio.json')));}
